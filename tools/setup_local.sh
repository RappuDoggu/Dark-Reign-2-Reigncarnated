#!/usr/bin/env bash
# Reproduce the Linux/WSL toolchain used by the existing launch APK.
# Run from an authenticated checkout. Does not install OS packages or sign APKs.
set -euo pipefail
repo=$(cd -- "$(dirname -- "$0")/.." && pwd)
work=${1:?Usage: bash tools/setup_local.sh /absolute/workspace-root}
mkdir -p "$work"
work=$(cd -- "$work" && pwd)
case "$work/" in "$repo/"*) echo 'Workspace must be outside the Git checkout.' >&2; exit 2;; esac
if [ "$(uname -s)" != Linux ] || [ "$(uname -m)" != x86_64 ]; then
 echo 'Use x86_64 Linux or WSL2. Current packaging scripts require Linux SDK tools.' >&2
 exit 2
fi
for cmd in git curl unzip tar python3 cmake ninja make g++ java javac keytool; do
 command -v "$cmd" >/dev/null || { echo "Missing prerequisite: $cmd (see docs/LOCAL_WINDOWS_SETUP.md)" >&2; exit 2; }
done
pin=9ce9da5f21604310a997f0c41e9cd383f5e292c3
if [ ! -e "$work/upstream" ]; then
 bash "$repo/tools/fetch_upstream.sh" "$work/upstream"
else
 [ "$(git -C "$work/upstream" rev-parse HEAD)" = "$pin" ] || { echo 'Existing upstream is not the pinned revision; leave it intact and choose a different workspace.' >&2; exit 2; }
 [ -z "$(git -C "$work/upstream" status --porcelain)" ] || { echo 'Existing upstream has changes; preserve it and choose a different workspace.' >&2; exit 2; }
fi
bash "$repo/tools/install_android_sdk.sh" "$work/sdk"
export ANDROID_SDK_ROOT="$work/sdk"
export ANDROID_NDK_HOME="$work/sdk/ndk/27.2.12479018"
python3 "$repo/tools/stage_khronos_headers.py" "$ANDROID_NDK_HOME" "$work/khronos"
for mode in host android; do
 if [ ! -f "$work/ffmpeg/$mode/install/lib/libavcodec.a" ]; then
  bash "$repo/tools/build_bink_decoder.sh" "$work/ffmpeg" "$mode"
 fi
done
mkdir -p "$work/owned" "$work/exports" "$work/logs" "$work/signing"
python3 - "$work" "$repo" <<'PY'
import pathlib, shlex, sys
w=pathlib.Path(sys.argv[1]); repo=sys.argv[2]
values={'REIGN_WORK_ROOT':str(w), 'REIGN_REPO':repo, 'REIGN_UPSTREAM':str(w/'upstream'),
        'ANDROID_SDK_ROOT':str(w/'sdk'), 'ANDROID_NDK_HOME':str(w/'sdk/ndk/27.2.12479018'),
        'REIGN_FFMPEG_ROOT':str(w/'ffmpeg/android/install'), 'REIGN_MENU_BUILD_DIR':str(w/'build-menu')}
(w/'env.sh').write_text('# Generated by tools/setup_local.sh\n' + ''.join('export '+k+'='+shlex.quote(v)+'\n' for k,v in values.items()))
PY
cmake -S "$repo" -B "$work/build-host" -G Ninja \
 -DREIGN_UPSTREAM="$work/upstream" -DREIGN_SANITIZE=ON \
 -DREIGN_GLES_BACKEND=ON -DREIGN_KHRONOS_HEADERS="$work/khronos" \
 -DREIGN_FFMPEG_ROOT="$work/ffmpeg/host/install"
cmake --build "$work/build-host" --parallel "${REIGN_BUILD_JOBS:-4}"
ASAN_OPTIONS=detect_leaks=0 LIBGL_ALWAYS_SOFTWARE=1 ctest --test-dir "$work/build-host" --output-on-failure
cmake -S "$repo/engine" -B "$work/build-engine-host" -G Ninja \
 -DREIGN_UPSTREAM="$work/upstream" -DREIGN_SANITIZE=ON
cmake --build "$work/build-engine-host" --parallel "${REIGN_BUILD_JOBS:-4}"
ASAN_OPTIONS=detect_leaks=0 ctest --test-dir "$work/build-engine-host" --output-on-failure
cmake -S "$repo/engine" -B "$work/build-engine-android" -G Ninja \
 -DREIGN_UPSTREAM="$work/upstream" \
 -DCMAKE_TOOLCHAIN_FILE="$ANDROID_NDK_HOME/build/cmake/android.toolchain.cmake" \
 -DANDROID_ABI=arm64-v8a -DANDROID_PLATFORM=android-26
cmake --build "$work/build-engine-android" --parallel "${REIGN_BUILD_JOBS:-4}"
printf '\nLocal toolchain and host checks complete.\nLoad your environment with: source %q\n' "$work/env.sh"
printf 'No mission APK was generated; see docs/INSTANT_ACTION_BRINGUP.md for gameplay status.\n'
